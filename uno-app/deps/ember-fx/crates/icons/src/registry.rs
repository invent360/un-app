//! Icon registry for managing icon sets.

/// Available icon sets.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IconSet {
    /// Heroicons by Tailwind CSS
    Heroicons,
    /// Lucide icons
    Lucide,
    /// Phosphor icons
    Phosphor,
    /// Custom icons
    Custom,
}

/// Common icon names available across icon sets.
///
/// These map to the most commonly used icons. Each icon set provides
/// its own implementation of these icons with consistent naming.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IconName {
    // Actions
    Check,
    Close,
    Plus,
    Minus,
    Edit,
    Delete,
    Save,
    Cancel,
    Refresh,

    // Navigation
    ChevronUp,
    ChevronDown,
    ChevronLeft,
    ChevronRight,
    ArrowUp,
    ArrowDown,
    ArrowLeft,
    ArrowRight,
    Menu,
    Home,

    // Status
    Info,
    Warning,
    Error,
    Success,
    Question,

    // UI Elements
    Search,
    Filter,
    Sort,
    Settings,
    User,
    Users,
    Bell,
    Mail,
    Calendar,
    Clock,

    // Media
    Image,
    Video,
    Audio,
    File,
    Folder,
    Download,
    Upload,
    Link,

    // Misc
    Star,
    Heart,
    Eye,
    EyeOff,
    Lock,
    Unlock,
    Copy,
    Clipboard,
}

